// Builds title.asm: the MODE 7 title screen, packed for draw_title, which reads it from
// the top left of a clear screen: 1-31 skips that many cells, 0 n b writes byte b n
// times (n = 0 ends), and anything else is written as it is. The high score names and
// digits, and the prompt text, are left blank: the game fills them in.
// Run: node tools/title.mjs
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const src = fs.readFileSync(path.join(ROOT, "galaxa.asm"), "utf8");
const art = {};
for (const m of src.matchAll(/^ART_(\w+)\s*=\s*(.+)$/gm)) art[m[1]] = [...m[2].matchAll(/"([0-9]+)"/g)].map((x) => [...x[1]].map(Number));

const A = { red: 129, green: 130, yellow: 131, blue: 132, magenta: 133, cyan: 134, white: 135 };
const G = { red: 145, green: 146, yellow: 147, blue: 148, magenta: 149, cyan: 150, white: 151 };
const FLASH = 136, SEP = 154;
const HS_ROW = 14, HS_COL = 10, PROMPT_ROW = 23, PROMPT_COL = 14;

const scr = [...Array(25)].map(() => Array(40).fill(32));
const put = (r, c, ...items) => { for (const it of items) for (const b of typeof it === "string" ? [...it].map((ch) => ch.charCodeAt(0)) : [it]) scr[r][c++] = b; };
// pixels to sixels: px[y][x] truthy, the block's top left at row r, column c
const SIX = [[1, 2], [4, 8], [16, 64]];
function mosaic(px, r, c) {
  for (let cy = 0; cy * 3 < px.length; cy++) for (let cx = 0; cx * 2 < px[0].length; cx++) {
    let v = 32;
    for (let y = 0; y < 3; y++) for (let x = 0; x < 2; x++) if (px[cy * 3 + y]?.[cx * 2 + x]) v |= SIX[y][x];
    scr[r + cy][c + cx] = v;
  }
}

// stars: separated white dots
let seed = 7;
const rnd = () => (seed = (seed * 75 + 74) % 65537) / 65537;
for (const r of [0, 6, 12]) {
  put(r, 0, G.white, SEP);
  for (let c = 2; c < 40; c++) if (rnd() < 0.18) scr[r][c] = 32 | SIX[Math.floor(rnd() * 3)][Math.floor(rnd() * 2)];
}

// GALAXA: a 4x7 font at 2x, 29 cells x 5 rows, centred
const F = {
  G: [".###", "#...", "#...", "#.##", "#..#", "#..#", ".###"],
  A: [".##.", "#..#", "#..#", "####", "#..#", "#..#", "#..#"],
  L: ["#...", "#...", "#...", "#...", "#...", "#...", "####"],
  X: ["#..#", "#..#", ".##.", ".##.", ".##.", "#..#", "#..#"],
};
const logo = [...Array(15)].map(() => []);
let lx = 0;
for (const ch of "GALAXA") {
  F[ch].forEach((row, y) => [...row].forEach((p, x) => {
    for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++) logo[y * 2 + dy][lx + x * 2 + dx] = p === "#";
  }));
  lx += F[ch][0].length * 2 + 2;
}
[G.white, G.cyan, G.cyan, G.blue, G.blue].forEach((g, i) => put(1 + i, 0, g));
mosaic(logo, 1, 6);

// the three aliens, from the game's own art, one colour each
[["FLAGSHIP", G.yellow], ["ESCORT", G.red], ["DRONE", G.magenta]].forEach(([name, g], i) => {
  const c = 7 + i * 11;
  for (let r = 8; r < 11; r++) put(r, c - 1, g);
  mosaic(art[name].map((row) => row.map((v) => v !== 0)), 8, c);
});

// high score rows: stage dots from HS_COL + 3, the score's 4 BCD digits at HS_COL + 16
["1", "2", "3", "4", "5"].forEach((rank, i) =>
  put(HS_ROW + i, HS_COL, A.white, rank, A.green, "............", A.yellow, "    0"));

put(20, 4, A.green, "Z LEFT    X RIGHT    RETURN FIRE");
put(PROMPT_ROW, PROMPT_COL - 2, A.white, FLASH);

// pack it: skips for spaces, runs of 4 or more, the rest as they are
const flat = scr.flat();
while (flat.at(-1) === 32) flat.pop();
const packed = [];
for (let i = 0; i < flat.length; ) {
  let j = i;
  while (j < flat.length && flat[j] === flat[i]) j++;
  let n = j - i;
  if (flat[i] === 32) for (; n > 0; n -= 31) packed.push(Math.min(n, 31));
  else if (n >= 4) for (; n > 0; n -= 255) packed.push(0, Math.min(n, 255), flat[i]);
  else packed.push(...flat.slice(i, j));
  i = j;
}
packed.push(0, 0);
const hex = (b) => "&" + b.toString(16).toUpperCase().padStart(2, "0");
const out = [
  "; Generated by tools/title.mjs: edit that, not this.",
  `HS_ROW = ${HS_ROW}`,
  `HS_COL = ${HS_COL}`,
  `PROMPT_ROW = ${PROMPT_ROW}`,
  `PROMPT_COL = ${PROMPT_COL}`,
  "ASSERT HS_DIGITS = 16 AND PROMPT_LEN = 13",
  ".title_screen",
  ...Array.from({ length: Math.ceil(packed.length / 16) }, (_, i) => "    EQUB " + packed.slice(i * 16, i * 16 + 16).map(hex).join(", ")),
  "",
];
fs.writeFileSync(path.join(ROOT, "title.asm"), out.join("\n"));
console.log(`title.asm: ${packed.length} bytes`);
